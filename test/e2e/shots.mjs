import fs from 'node:fs'
import path from 'node:path'

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

export default async function run({ engine, win, app }) {
  const m = JSON.parse(fs.readFileSync(process.env.RENDERFARM_E2E_MANIFEST, 'utf8'))
  fs.mkdirSync(m.shots, { recursive: true })
  const js = (code) => win.webContents.executeJavaScript(code)
  const shot = async (name) => {
    await sleep(500)
    const img = await win.webContents.capturePage()
    fs.writeFileSync(path.join(m.shots, `${name}.png`), img.toPNG())
    console.log('shot', name)
  }
  const waitFor = async (cond, ms = 60000) => {
    const t0 = Date.now()
    while (!cond()) {
      if (Date.now() - t0 > ms) throw new Error('timeout')
      await sleep(100)
    }
  }
  const clickText = (sel, text) => js(`[...document.querySelectorAll(${JSON.stringify(sel)})].find(b => b.textContent.includes(${JSON.stringify(text)}))?.click()`)
  const clickRow = (i) => js(`document.querySelectorAll('.rows .row')[${i}]?.dispatchEvent(new MouseEvent('click', { bubbles: true }))`)
  const esc = () => js(`window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' }))`)
  try {
    win.setContentSize(1440, 900)
    await waitFor(() => !win.webContents.isLoading())
    await sleep(1500)
    engine.addInstall(m.mock)
    engine.addInstall(m.mockBlender)
    await shot('01-empty')

    engine.updateGlobal({ outputRoot: m.out, format: 'png' })
    engine.updateApp({ concurrency: 2, completionKind: 'shutdown', completionAction: 'none', countdownSeconds: 30, maxRetries: 2, logOpen: false, logHeight: 210 })
    engine.addPaths([m.scenes])
    await waitFor(() => engine.jobs.length === 8 && engine.jobs.every((j) => j.info.state === 'done'))
    engine.updateJobs([engine.jobs.find((j) => j.sceneName === 'SQ02_SH030').id], { enabled: false })
    await shot('02-queue-ready')

    await js(`document.querySelector('.header .btn.primary').click()`)
    await sleep(600)
    await shot('03-preflight')
    await clickText('.modal .issue-item .link', '타임라인 범위 사용')
    await sleep(500)
    await shot('04-preflight-fixed')
    await clickText('.modal .btn.primary', '시작')
    await js(`document.querySelector('.cbox').click()`)
    await sleep(7000)
    await shot('05-rendering')

    await clickRow(3)
    await js(`document.querySelectorAll('.rows .row')[3].dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))`)
    await sleep(700)
    await shot('06-details')
    await js(`document.querySelector('details.more')?.setAttribute('open', '')`)
    await sleep(400)
    await shot('07-details-advanced')
    await esc()

    await clickRow(2)
    await clickText('.queue-head .btn', '로그')
    await sleep(600)
    await shot('08-log')
    await clickText('.queue-head .btn', '로그')

    await js(`document.querySelector('[aria-label="환경 설정"]').click()`)
    await sleep(500)
    await shot('09-settings')
    await clickText('.settings-nav button', '끝난 뒤 작업')
    await sleep(300)
    await shot('10-settings-after')
    await esc()

    await waitFor(() => engine.completion.pendingAction !== null, 120000)
    await sleep(2200)
    await shot('11-countdown')
    engine.cancelCountdown()
    await sleep(800)
    await js(`document.querySelectorAll('.rows .row')[0]?.dispatchEvent(new MouseEvent('click', { bubbles: true }))`)
    await shot('12-finished')

    engine.setPin('2580')
    engine.lockNow()
    engine.resetJobs(engine.jobs.map((j) => j.id), 'full')
    engine.updateJobs([engine.jobs.find((j) => j.sceneName === 'SQ02_SH030').id], { enabled: false })
    await sleep(600)
    await shot('13-locked-student')
    await js(`document.querySelector('[aria-label="환경 설정"]').click()`)
    await sleep(400)
    await shot('14-pin')
    await esc()
    win.setContentSize(1120, 680)
    await sleep(600)
    await shot('15-min-size')
    win.setContentSize(1920, 1080)
    await sleep(600)
    await shot('16-large')
    engine.unlock('2580')
    engine.updateGlobal({ outputRoot: path.join(m.out, 'SQ01_SH010') })
    win.setContentSize(1440, 900)
    await sleep(600)
    await shot('17-nested-folder')
    engine.updateGlobal({ outputRoot: m.out })
    const bi = engine.jobs.findIndex((j) => j.app === 'blender')
    await clickRow(bi)
    await js(`document.querySelectorAll('.rows .row')[${bi}].dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))`)
    await sleep(600)
    await js(`document.querySelectorAll('details.more').forEach((d) => d.setAttribute('open', ''))`)
    await sleep(400)
    await shot('18-blender-details')
    await esc()
    await js(`document.querySelector('[aria-label="환경 설정"]').click()`)
    await sleep(400)
    await clickText('.settings-nav button', '프로그램')
    await sleep(300)
    await shot('19-settings-programs')
    await esc()
    const summary = engine.jobs.map((j) => `${j.sceneName}: ${j.status} ${j.doneFrames.length}/${j.frames.length}`)
    fs.writeFileSync(path.join(m.shots, 'summary.txt'), summary.join('\n') + '\n')
  } catch (e) {
    console.error('E2E FAILED', e)
    await shot('error')
  } finally {
    setTimeout(() => app.exit(0), 300)
  }
}
